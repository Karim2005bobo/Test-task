def has_glyph(ch: str) -> bool:
    return ch in GLYPHS


def draw_char(img, ch, x, y, w, h, stroke, color, jitter=None):
    """Рисует символ в прямоугольнике (x, y, w, h), координаты в пикселях.

    Рисование идёт с субпиксельной точностью (shift=4) и сглаживанием.
    """
    strokes = GLYPHS[ch]
    # Штрих рисуется по центру линии, поэтому сужаем рабочую область на полштриха.
    ix, iy = x + stroke / 2, y + stroke / 2
    iw, ih = max(w - stroke, 1), max(h - stroke, 1)
    sh = 16
    for s in strokes:
        pts = []
        dx, dy = (jitter.normal(0, 0.008, 2) if jitter is not None else (0.0, 0.0))
        for px, py in s:
            px, py = px + dx, py + dy
            pts.append((int(round((ix + px * iw) * sh)), int(round((iy + py * ih) * sh))))
        cv2.polylines(img, [np.array(pts, np.int32)], False, color,
                      thickness=max(1, int(round(stroke))), lineType=cv2.LINE_AA, shift=4)
