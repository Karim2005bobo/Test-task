"""Собственный штриховой шрифт, приближающий начертание символов ГРЗ
по ГОСТ Р 50577-2018 (узкий гротеск постоянной толщины штриха).

Каждый глиф описан набором ломаных в единичном квадрате [0,1]x[0,1]
(ось y направлена вниз). Шрифт полностью авторский, поэтому на синтетику
не распространяются чужие лицензии на шрифты.
"""
import math

import cv2
import numpy as np


def _arc(cx, cy, rx, ry, a0, a1, n=24):
    ts = np.linspace(math.radians(a0), math.radians(a1), n)
    return [(cx + rx * math.cos(t), cy + ry * math.sin(t)) for t in ts]


def _stadium(cx, rx, top, bottom):
    """Вертикальный «стадион» (как у цифры 0)."""
    r = rx
    ry = min(r * 1.1, (bottom - top) / 2)
    pts = _arc(cx, top + ry, rx, ry, 180, 360)
    pts += _arc(cx, bottom - ry, rx, ry, 0, 180)
    pts.append(pts[0])
    return pts


def _rot180(strokes):
    return [[(1 - x, 1 - y) for x, y in s] for s in strokes]


